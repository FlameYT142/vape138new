async def seed_rules():
    for code, text, dur, dur_text, crit, rec_a, rec_s, rec_t, special in RULES_SEED:
        existing = await get_rule(code)
        if existing:
            continue
        await add_rule(code, text, dur, dur_text, crit, rec_a, rec_s, rec_t, special)
        if special == "inactive":
            await set_rule_active(code, 0)